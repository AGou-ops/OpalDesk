abstract class GenerateBridgeBuildConfigTask : DefaultTask() {
    @get:Input
    abstract val expectedHelperCertSha256: Property<String>

    @get:Input
    abstract val helperPackage: Property<String>

    @get:Input
    abstract val opalCastProtocolVersion: Property<Int>

    @get:Input
    abstract val signingSource: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val pkgDir = outputDir.get().asFile.resolve("io/github/lengsukq/opaldesk/daemon")
        pkgDir.mkdirs()
        val outFile = pkgDir.resolve("BridgeBuildConfig.java")
        val content = """
            package io.github.lengsukq.opaldesk.daemon;

            /**
             * Auto-generated by :bridge:generateBridgeBuildConfig (signing source: ${signingSource.get()}).
             * Do not edit manually.
             */
            public final class BridgeBuildConfig {
                public static final String EXPECTED_HELPER_CERT_SHA256 = "${expectedHelperCertSha256.get()}";
                public static final String HELPER_PACKAGE = "${helperPackage.get()}";
                public static final int OPALCAST_PROTOCOL_VERSION = ${opalCastProtocolVersion.get()};

                private BridgeBuildConfig() {
                }
            }
        """.trimIndent() + "\n"
        if (!outFile.exists() || outFile.readText(Charsets.UTF_8) != content) {
            outFile.writeText(content, Charsets.UTF_8)
        }
    }
}

abstract class DexBridgeJarTask : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val classesDir: DirectoryProperty

    @get:Input
    abstract val d8ExecutablePath: Property<String>

    @get:Input
    abstract val javaHomePath: Property<String>

    @get:OutputFile
    abstract val outputJar: RegularFileProperty

    @get:Inject
    abstract val execOperations: ExecOperations

    @TaskAction
    fun dex() {
        val classesRoot = classesDir.get().asFile
        val relClassFiles = classesRoot.walkTopDown()
            .filter { it.isFile && it.extension == "class" }
            .map { it.relativeTo(classesRoot).invariantSeparatorsPath }
            .sorted()
            .toList()

        if (relClassFiles.isEmpty()) {
            throw GradleException("No compiled .class files found under ${classesRoot.absolutePath}")
        }

        val outFile = outputJar.get().asFile
        outFile.parentFile.mkdirs()
        if (outFile.exists()) {
            outFile.delete()
        }

        val command = mutableListOf(
            d8ExecutablePath.get(),
            "--min-api",
            "30",
            "--output",
            outFile.absolutePath,
        )
        command.addAll(relClassFiles)

        execOperations.exec {
            workingDir(classesRoot)
            environment("JAVA_HOME", javaHomePath.get())
            commandLine(command)
        }

        if (!outFile.isFile || outFile.length() == 0L) {
            throw GradleException("d8 completed without producing non-empty ${outFile.absolutePath}")
        }

        // Normalize ZIP headers (clear streaming Data Descriptor flag 0x0008 and pin deterministic timestamp)
        // for full compatibility with older Android Toybox unzip implementations and reproducible builds.
        normalizeZipArchive(outFile)
    }

    private fun normalizeZipArchive(zipPath: File) {
        val entries = mutableListOf<Pair<String, ByteArray>>()
        ZipFile(zipPath).use { zf ->
            val enum = zf.entries()
            while (enum.hasMoreElements()) {
                val entry = enum.nextElement()
                if (!entry.isDirectory) {
                    entries.add(entry.name to zf.getInputStream(entry).readBytes())
                }
            }
        }
        entries.sortBy { it.first }
        // Deterministic DOS date/time: 2026-01-01 00:00:00
        val dosTime = 0
        val dosDate = ((2026 - 1980) shl 9) or (1 shl 5) or 1

        fun putU16(out: ByteArrayOutputStream, v: Int) {
            out.write(v and 0xFF)
            out.write((v ushr 8) and 0xFF)
        }
        fun putU32(out: ByteArrayOutputStream, v: Long) {
            out.write((v and 0xFF).toInt())
            out.write(((v ushr 8) and 0xFF).toInt())
            out.write(((v ushr 16) and 0xFF).toInt())
            out.write(((v ushr 24) and 0xFF).toInt())
        }

        data class WrittenEntry(
            val nameBytes: ByteArray,
            val method: Int,
            val crc: Long,
            val compSize: Long,
            val uncompSize: Long,
            val localHeaderOffset: Long,
        )

        val archive = ByteArrayOutputStream()
        val cdRecords = mutableListOf<WrittenEntry>()
        for ((name, rawBytes) in entries) {
            val nameBytes = name.toByteArray(Charsets.UTF_8)
            val crc = CRC32().apply { update(rawBytes) }.value
            val deflater = Deflater(Deflater.DEFAULT_COMPRESSION, true)
            deflater.setInput(rawBytes)
            deflater.finish()
            val compBuf = ByteArray(maxOf(rawBytes.size + 64, 128))
            val compOut = ByteArrayOutputStream()
            while (!deflater.finished()) {
                val count = deflater.deflate(compBuf)
                if (count > 0) compOut.write(compBuf, 0, count)
            }
            deflater.end()
            val deflated = compOut.toByteArray()
            val useStored = deflated.size >= rawBytes.size
            val payload = if (useStored) rawBytes else deflated
            val method = if (useStored) ZipEntry.STORED else ZipEntry.DEFLATED

            val offset = archive.size().toLong()
            // Local File Header with general purpose bit flag = 0x0000 (no bit 3 streaming descriptor)
            putU32(archive, 0x04034B50L)
            putU16(archive, 20)
            putU16(archive, 0)
            putU16(archive, method)
            putU16(archive, dosTime)
            putU16(archive, dosDate)
            putU32(archive, crc)
            putU32(archive, payload.size.toLong())
            putU32(archive, rawBytes.size.toLong())
            putU16(archive, nameBytes.size)
            putU16(archive, 0)
            archive.write(nameBytes)
            archive.write(payload)

            cdRecords.add(WrittenEntry(nameBytes, method, crc, payload.size.toLong(), rawBytes.size.toLong(), offset))
        }

        val cdOffset = archive.size().toLong()
        for (rec in cdRecords) {
            putU32(archive, 0x02014B50L)
            putU16(archive, 20)
            putU16(archive, 20)
            putU16(archive, 0)
            putU16(archive, rec.method)
            putU16(archive, dosTime)
            putU16(archive, dosDate)
            putU32(archive, rec.crc)
            putU32(archive, rec.compSize)
            putU32(archive, rec.uncompSize)
            putU16(archive, rec.nameBytes.size)
            putU16(archive, 0)
            putU16(archive, 0)
            putU16(archive, 0)
            putU16(archive, 0)
            putU32(archive, 0)
            putU32(archive, rec.localHeaderOffset)
            archive.write(rec.nameBytes)
        }
        val cdSize = archive.size().toLong() - cdOffset
        // End of Central Directory
        putU32(archive, 0x06054B50L)
        putU16(archive, 0)
        putU16(archive, 0)
        putU16(archive, cdRecords.size)
        putU16(archive, cdRecords.size)
        putU32(archive, cdSize)
        putU32(archive, cdOffset)
        putU16(archive, 0)

        val tmpFile = File(zipPath.parentFile, "${zipPath.name}.norm.tmp")
        FileOutputStream(tmpFile).use { it.write(archive.toByteArray()) }
        if (!tmpFile.renameTo(zipPath)) {
            tmpFile.copyTo(zipPath, overwrite = true)
            tmpFile.delete()
        }
    }
}

val generateBridgeBuildConfig = tasks.register<GenerateBridgeBuildConfigTask>("generateBridgeBuildConfig") {
    group = "build"
    description = "Generates BridgeBuildConfig.java with the resolved helper certificate SHA-256."
    expectedHelperCertSha256.set(rootProject.extra["opalDeskCertSha256"] as String)
    helperPackage.set("io.github.lengsukq.opaldesk")
    opalCastProtocolVersion.set(1)
    signingSource.set(rootProject.extra["opalDeskSigningSource"] as String)
    outputDir.set(layout.buildDirectory.dir("generated/bridgeConfig"))
}

