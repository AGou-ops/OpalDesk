fun resolveSdkDir(): File {
    val fromRoot = (rootProject.extra["extBridgeAndroidSdkDir"] as? String).orEmpty()
    if (fromRoot.isNotBlank()) {
        val f = File(fromRoot)
        if (f.isDirectory) return f
    }
    throw GradleException(
        "Android SDK directory not found. Set sdk.dir in local.properties or ANDROID_HOME / ANDROID_SDK_ROOT."
    )
}

fun parsePlatformApiVersion(dirName: String): Double? {
    val match = Regex("^android-(\\d+(?:\\.\\d+)?)").find(dirName) ?: return null
    return match.groupValues[1].toDoubleOrNull()
}

fun resolveAndroidJar(sdkDir: File): File {
    val preferred372 = File(sdkDir, "platforms/android-37.2/android.jar")
    if (preferred372.isFile) return preferred372
    val preferred = File(sdkDir, "platforms/android-37.0/android.jar")
    if (preferred.isFile) return preferred

    val platformsDir = File(sdkDir, "platforms")
    val candidates = platformsDir.listFiles()
        ?.filter { it.isDirectory }
        ?.mapNotNull { dir ->
            val api = parsePlatformApiVersion(dir.name)
            val jar = File(dir, "android.jar")
            if (api != null && api >= 30.0 && jar.isFile) api to jar else null
        }
        ?.sortedByDescending { it.first }
        .orEmpty()

    return candidates.firstOrNull()?.second ?: throw GradleException(
        "No Android platform android.jar (API >= 30) found under ${platformsDir.absolutePath}."
    )
}

fun parseVersionTuple(dirName: String): List<Int> =
    dirName.substringBefore('-')
        .split('.')
        .map { it.toIntOrNull() ?: 0 }

fun resolveD8Executable(sdkDir: File): File {
    val isWindows = System.getProperty("os.name").lowercase().contains("win")
    val d8Name = if (isWindows) "d8.bat" else "d8"

    val preferred = File(sdkDir, "build-tools/37.0.0/$d8Name")
    if (preferred.isFile) return preferred

    val buildToolsDir = File(sdkDir, "build-tools")
    val candidates = buildToolsDir.listFiles()
        ?.filter { it.isDirectory }
        ?.mapNotNull { dir ->
            val exe = File(dir, d8Name)
            if (exe.isFile) dir to exe else null
        }
        ?.sortedWith(
            compareByDescending<Pair<File, File>> { parseVersionTuple(it.first.name).getOrElse(0) { 0 } }
                .thenByDescending { parseVersionTuple(it.first.name).getOrElse(1) { 0 } }
                .thenByDescending { parseVersionTuple(it.first.name).getOrElse(2) { 0 } }
        )
        .orEmpty()

    return candidates.firstOrNull()?.second ?: throw GradleException(
        "Android SDK build-tools ($d8Name) not found under ${buildToolsDir.absolutePath}. " +
            "Install build-tools;37.0.0 via sdkmanager."
    )
}

